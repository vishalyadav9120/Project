
#python Operators Complete Program
a=10
b=5

print("a:",a)
print("b:",b)

#-- Arithmetic Operators --
print("add :",a+b) #addition
print("sub :",a-b) #subtract
print("mul :",a*b) # multiplication
print("div :",a/b) #division
print("mod :",a%b) #modulus
print("pow :",a**b) #power

#-- Comparison Operators --

print("a == b :", a == b)  #false
print("a != b :", a != b) #true
print("a > b :", a > b) #true
print("a < b :", a < b) #false
print("a >= b :", a >= b) #true
print("a <= b :", a <= b) #false

# Logical Operators
x = True
y = False

print("\nLogical Operators")
print("x and y =", x and y)
print("x or y =", x or y)
print("not x =", not x)

# Assignment Operators
c = 10
c += 5
print("\nAssignment Operator (+=)")
print("c =", c)
