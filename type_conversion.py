# String to Integer Conversion

a = "10"

print("Original Value:", a)
print("Original Data Type:", type(a)) #<str>

# Convert string to integer
b = int(a)

print("\nAfter Conversion")
print("Value of b:", b)
print("Data Type of b:", type(b)) #int

# Addition
result = b + 5

print("\nAddition Result")
print("b + 5 =", result) #int